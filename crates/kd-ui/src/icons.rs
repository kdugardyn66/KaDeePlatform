//! The icons, as SVG files under `icons/` (in the style of Lucide, ISC licence).
//! GPUI draws an SVG as a mask in the element's text colour.

/// Every icon the shell draws.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Icon {
    Home,
    FilePlus,
    File,
    FolderOpen,
    Folder,
    FolderPlus,
    Clock,
    Star,
    StarFilled,
    Grid,
    Plus,
    ChevronDown,
    ChevronRight,
    CaretDown,
    CaretUp,
    Settings,
    Sparkles,
    Sun,
    Moon,
    Contrast,
    X,
    Search,
    Refresh,
    More,
    ArrowUp,
    Stop,
    Copy,
    External,
    Check,
    Info,
    Key,
    Cpu,
    Keyboard,
    Eye,
    EyeOff,
    Trash,
    Spark,
}

impl Icon {
    /// The asset path GPUI loads it from (served by [`load`]).
    pub fn path(self) -> &'static str {
        match self {
            Icon::Home => "icons/home.svg",
            Icon::FilePlus => "icons/file-plus.svg",
            Icon::File => "icons/file.svg",
            Icon::FolderOpen => "icons/folder-open.svg",
            Icon::Folder => "icons/folder.svg",
            Icon::FolderPlus => "icons/folder-plus.svg",
            Icon::Clock => "icons/clock.svg",
            Icon::Star => "icons/star.svg",
            Icon::StarFilled => "icons/star-filled.svg",
            Icon::Grid => "icons/grid.svg",
            Icon::Plus => "icons/plus.svg",
            Icon::ChevronDown => "icons/chevron-down.svg",
            Icon::ChevronRight => "icons/chevron-right.svg",
            Icon::CaretDown => "icons/caret-down.svg",
            Icon::CaretUp => "icons/caret-up.svg",
            Icon::Settings => "icons/settings.svg",
            Icon::Sparkles => "icons/sparkles.svg",
            Icon::Sun => "icons/sun.svg",
            Icon::Moon => "icons/moon.svg",
            Icon::Contrast => "icons/contrast.svg",
            Icon::X => "icons/x.svg",
            Icon::Search => "icons/search.svg",
            Icon::Refresh => "icons/refresh.svg",
            Icon::More => "icons/more.svg",
            Icon::ArrowUp => "icons/arrow-up.svg",
            Icon::Stop => "icons/stop.svg",
            Icon::Copy => "icons/copy.svg",
            Icon::External => "icons/external.svg",
            Icon::Check => "icons/check.svg",
            Icon::Info => "icons/info.svg",
            Icon::Key => "icons/key.svg",
            Icon::Cpu => "icons/cpu.svg",
            Icon::Keyboard => "icons/keyboard.svg",
            Icon::Eye => "icons/eye.svg",
            Icon::EyeOff => "icons/eye-off.svg",
            Icon::Trash => "icons/trash.svg",
            Icon::Spark => "icons/spark.svg",
        }
    }
}

